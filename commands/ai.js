const axios = require('axios');
const gemini = require('../lib/gemini');
const theme = require('../lib/theme');
const config = require('../config');

module.exports = {
  ai: {
    desc: "Ask anything to AI Assistant",
    category: "ai",
    execute: async (sock, m, { args, text, reply, prefix }) => {
      if (!text) {
        return reply(theme.errorCard('ai', `Poochho kya poochna hai!\nExample: \`${prefix}ai Pakistan ka sab se bara shehar konsa hai?\``));
      }

      await reply(theme.resultCard('🧠', 'AI NEURAL THINKING', [
        `💬 *Query:* "${text.substring(0, 45)}${text.length > 45 ? '...' : ''}"`,
        `⚡ *Engine:* Smart AI Assistant`,
        `⏳ *Status:* Processing Answer...`
      ]));

      const answer = await gemini.ask(text);
      const output = `┌───「 🧠 *TALHA-MD AI INTELLIGENCE* 」───
│ ❓ *Question:* ${text}
└──────────────────────────────────────

${answer}

──────────────────────────────────────
_⚡ Powered by TALHA-MD • Super-Smart Assistant_`;

      await reply(output);
    }
  },

  img: {
    desc: "Generate HD AI image from text prompt",
    category: "ai",
    execute: async (sock, m, { text, reply, from, prefix }) => {
      if (!text) {
        return reply(theme.errorCard('img', `Prompt likhein!\nExample: \`${prefix}img cyber sports car with neon lights in rain\` ya \`${prefix}img cute kitten in astronaut suit\``));
      }

      await reply(theme.resultCard('🎨', 'AI ART ENGINE ACTIVE', [
        `🖌️ *Prompt:* "${text.substring(0, 40)}..."`,
        `🖼️ *Resolution:* 800x800 HD`,
        `⏳ *Status:* Rendering Pixels...`
      ], 'Bas 3-5 seconds intezar karein! ✨'));

      try {
        const imageUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(text)}?width=800&height=800&nologo=true`;
        const res = await axios.get(imageUrl, { responseType: 'arraybuffer', timeout: 25000 });

        const caption = theme.resultCard('🎨', 'AI ARTWORK GENERATED', [
          `🖌️ *Prompt:* "${text}"`,
          `✨ *Quality:* Ultra HD Render`,
          `👑 *Generated by:* ${config.BOT_NAME}`
        ], 'Obsidian Creative Engine');

        await sock.sendMessage(from, {
          image: Buffer.from(res.data),
          caption: caption
        }, { quoted: m });
      } catch (e) {
        console.error('[Command .img error]:', e);
        await reply(theme.errorCard('img', `Image generation error: ${e.message}`));
      }
    }
  },

  draw: {
    desc: "Alias for .img",
    category: "ai",
    execute: async (sock, m, extra) => {
      return module.exports.img.execute(sock, m, extra);
    }
  },

  roast: {
    desc: "Hilarious witty roast on a message",
    category: "ai",
    execute: async (sock, m, { reply, quotedText, text, prefix }) => {
      const target = quotedText || text;
      if (!target) {
        return reply(theme.errorCard('roast', `Kisi ke message par reply karke \`${prefix}roast\` likhein, ya direct likhein:\n\`${prefix}roast Mera dost bohot ajeeb hai\``));
      }

      await reply(theme.resultCard('🔥', 'SAVAGE ROAST INCOMING', [
        `🎯 *Target:* "${target.substring(0, 35)}..."`,
        `⚡ *Heat Level:* Maximum`,
        `⏳ *Cooking roast...*`
      ]));

      const roastText = await gemini.roast(target);
      const output = `┌───「 🔥 *TALHA-MD SAVAGE ROAST* 」───
│ 🎯 *Original:* "${target}"
└──────────────────────────────────────

${roastText}

──────────────────────────────────────
_🔥 Obsidian Sarcasm • Burn Cream Not Included!_`;

      await reply(output);
    }
  },

  detect: {
    desc: "Lie detector test on a message",
    category: "ai",
    execute: async (sock, m, { reply, quotedText, text, prefix }) => {
      const target = quotedText || text;
      if (!target) {
        return reply(theme.errorCard('detect', `Kisi ke message par reply karke \`${prefix}detect\` likhein!\n(e.g. 'bhai kal pakka paise wapis dunga')`));
      }

      await reply(theme.resultCard('🔍', 'POLYGRAPH SCAN ACTIVE', [
        `🎯 *Statement:* "${target.substring(0, 35)}..."`,
        `🧠 *Biometrics:* Voice Tone & Pitch Analysis`,
        `⏳ *Scanning for truth...*`
      ]));

      const report = await gemini.detectLie(target);
      const output = `┌───「 🚨 *LIE DETECTOR TRUTH VERDICT* 」───
│ 🔍 *Statement:* "${target}"
└─────────────────────────────────────────

${report}

─────────────────────────────────────────
_💯 High-Accuracy Forensic Lie Detector • TALHA-MD_`;

      await reply(output);
    }
  },

  summary: {
    desc: "Summarize text or quoted messages",
    category: "ai",
    execute: async (sock, m, { reply, quotedText, text, prefix }) => {
      const target = quotedText || text;
      if (!target) {
        return reply(theme.errorCard('summary', `Kisi lambi chat ya message par reply karke \`${prefix}summary\` likhein!`));
      }

      await reply(theme.resultCard('📝', 'ANALYZING THREAD', [
        `📄 *Length:* ${target.length} characters`,
        `🧠 *Method:* Key point extraction`,
        `⏳ *Generating summary...*`
      ]));

      const sum = await gemini.summarize(target);
      const output = `┌───「 📋 *CHAT SUMMARY (CRISP NICHOD)* 」───
│ 📝 *Extracted Highlights*
└─────────────────────────────────────────

${sum}

─────────────────────────────────────────
_⚡ Instant Intelligence by TALHA-MD_`;

      await reply(output);
    }
  }
};
